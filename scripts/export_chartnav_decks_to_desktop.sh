# scripts/export_chartnav_decks_to_desktop.sh — Phase 17 desktop
# demo delivery package exporter.
#
# What it does:
#   1. Recreates (or reuses) the operator's Desktop demo folder at
#      $CHARTNAV_DESKTOP_DIR (default
#      "/Users/jean-maxcharles/Desktop/chartnav decks").
#   2. Copies every Markdown source doc listed in the source-of-truth
#      contract (docs/chartnav-desktop-demo-delivery-package.md) to
#      its destination subfolder.
#   3. Generates the README.md at the Desktop folder root.
#   4. Generates three .command files in 08_Local_Demo_Launcher/
#      (START_CHARTNAV / STOP_CHARTNAV / RESET_DEMO_DATA) and marks
#      them executable.
#   5. Prints a summary tree.
#
# The Desktop folder is a *generated review package*, not source.
# The repo source under docs/ and scripts/ is the only source of
# truth. Desktop content is regenerated by running this script.
#
# Safety:
#   - Reads only from docs/, scripts/, and a known set of brand/text
#     assets. Does not read secrets, PHI, or backend code.
#   - Does not generate binary media (PNG/JPG/PDF/MP4/etc.).
#   - The reset .command file wraps scripts/reset_demo_state.sh,
#     which already refuses non-local DATABASE_URL values.
#   - The Desktop folder paths are listed in .gitignore so the
#     generated package is never committed.
#
# Usage:
#   bash scripts/export_chartnav_decks_to_desktop.sh
#
# Override the destination (e.g., for CI/dev users):
#   CHARTNAV_DESKTOP_DIR="$HOME/Desktop/chartnav decks" \
#     bash scripts/export_chartnav_decks_to_desktop.sh
#
# Exit codes:
#   0  export complete
#   1  required source file missing
#   2  filesystem error (mkdir / cp / chmod)

