## How to run a demo

1. Open `08_Local_Demo_Launcher/`.
2. Double-click `START_CHARTNAV.command`. A Terminal window opens,
   the local stack boots, and the browser opens to
   `http://localhost:5173/?demo=1`.
3. Walk the Guided Demo Mode 8-step path. Use the demo script in
   `03_Demo_Package/` for what to say and the click path for what
   to click.
4. After the demo, double-click `RESET_DEMO_DATA.command` to wipe
   the local SQLite dev DB and re-seed the fake demo data.
5. To stop the stack, double-click `STOP_CHARTNAV.command`.

If anything looks off, open
`08_Local_Demo_Launcher/chartnav-local-demo-troubleshooting.md`.

