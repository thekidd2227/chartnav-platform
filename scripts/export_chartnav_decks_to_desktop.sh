#!/usr/bin/env bash
# STOP_CHARTNAV.command — generated by
# scripts/export_chartnav_decks_to_desktop.sh
#
# Stops the ChartNav local stack by terminating processes bound
# to the standard dev ports (:8000 API, :5173 frontend). Does not
# kill unrelated processes.

set -uo pipefail

echo "ChartNav local demo — stop."
echo

stop_port() {
  local port="$1"
  if ! command -v lsof >/dev/null 2>&1; then
    echo "  skip — lsof not available, cannot inspect :$port"
    return
  fi
  local pids
  pids="$(lsof -ti tcp:"$port" 2>/dev/null || true)"
  if [ -z "$pids" ]; then
    echo "  ok — nothing bound to :$port"
    return
  fi
  echo "  stopping pid(s) $pids on :$port (SIGTERM)…"
  # SIGTERM only — never SIGKILL unrelated processes.
  kill $pids 2>/dev/null || true
  sleep 1
  pids="$(lsof -ti tcp:"$port" 2>/dev/null || true)"
  if [ -n "$pids" ]; then
    echo "  warn — pid(s) $pids still bound to :$port; you may need to stop manually."
  else
    echo "  ok — :$port is free."
  fi
}

